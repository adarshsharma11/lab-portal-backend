interface ParsedMasterTest {
  itemId: string;
  code: string;
  name: string;
  department: string;
  rate: number;
  mrp: number;
  sampleType: string;
}

function parseTests(): ParsedMasterTest[] {
  const lines = rawTestData.trim().split("\n");
  let currentDepartment = "Biochemistry";
  const results: ParsedMasterTest[] = [];

  const deptMap: Record<string, string> = {
    BIOCHEMISTRY: "Biochemistry",
    "CLINICAL PATHOLOGY": "Clinical Pathology",
    CYTOGENETICS: "Cytogenetics",
    CYTOLOGY: "Cytology",
    "FLOW CYTOMETRY": "Flow Cytometry",
    HAEMATOLOGY: "Hematology",
    HISTOPATHOLOGY: "Histopathology",
    IMMUNOLOGY: "Immunology",
    "MATERNAL MARKER": "Maternal Marker",
    MICROBIOLOGY: "Microbiology",
    "MOLECULAR BIOLOGY": "Molecular Biology",
    "OPD PACKAGE": "OPD Package",
    SEROLOGY: "Serology",
    "SPECIAL TESTS": "Special Tests",
  };

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) continue;

    const upper = line.toUpperCase();
    if (deptMap[upper]) {
      currentDepartment = deptMap[upper];
      continue;
    }

    const parts = line.split(/\t+|\s{2,}/).map((p) => p.trim()).filter(Boolean);
    if (parts.length >= 4) {
      const itemId = parts[0];
      const code = parts[1];
      // When line is e.g. "LSHHI6344 HM001 17-OH KETOSTEROIDS - 24HRS. URINE 3040 5080"
      // or "LSHHI7163 MC095 DMD DUCHENNE MUSCULAR DYSTROPHY 6000"
      let mrp = 0;
      let rate = 0;
      let name = "";

      if (parts.length === 5) {
        name = parts[2];
        rate = parseFloat(parts[3]) || 0;
        mrp = parseFloat(parts[4]) || 0;
      } else if (parts.length === 4) {
        name = parts[2];
        rate = parseFloat(parts[3]) || 0;
        mrp = rate;
      } else if (parts.length > 5) {
        // Name had spaces/tabs
        const last = parseFloat(parts[parts.length - 1]);
        const secondLast = parseFloat(parts[parts.length - 2]);
        if (!isNaN(last) && !isNaN(secondLast)) {
          mrp = last;
          rate = secondLast;
          name = parts.slice(2, parts.length - 2).join(" ");
        } else if (!isNaN(last)) {
          rate = last;
          mrp = last;
          name = parts.slice(2, parts.length - 1).join(" ");
        }
      }

      // Infer sample type from name/department
      let sampleType = "Blood";
      const nameUpper = name.toUpperCase();
      if (nameUpper.includes("URINE")) sampleType = "Urine";
      else if (nameUpper.includes("CSF")) sampleType = "CSF";
      else if (nameUpper.includes("FLUID") || nameUpper.includes("ASCITIC") || nameUpper.includes("PLEURAL") || nameUpper.includes("SYNOVIAL")) sampleType = "Fluid";
      else if (nameUpper.includes("STOOL")) sampleType = "Stool";
      else if (nameUpper.includes("SWAB") || nameUpper.includes("SPUTUM") || nameUpper.includes("SEMEN") || nameUpper.includes("BIOPSY") || nameUpper.includes("SMEAR")) sampleType = "Other";
      else if (nameUpper.includes("SERUM")) sampleType = "Serum";
      else if (nameUpper.includes("PLASMA")) sampleType = "Plasma";

      results.push({
        itemId,
        code,
        name,
        department: currentDepartment,
        rate,
        mrp: mrp || rate,
        sampleType,
      });
    }
  }

  return results;
}

export async function seedTestMasters() {
  const tests = parseTests();
  console.log(`Parsed ${tests.length} test master entries. Seeding into database...`);

  // Clear existing TestMaster records if any, then insert all in batch
  await prisma.testMaster.deleteMany({});

  const created = await prisma.testMaster.createMany({
    data: tests.map((t) => ({
      itemId: t.itemId,
      code: t.code,
      name: t.name,
      department: t.department,
      rate: t.rate,
      mrp: t.mrp,
      sampleType: t.sampleType,
      turnaroundHours: 24,
      status: "Active",
    })),
  });

  console.log(`Successfully seeded ${created.count} TestMaster records!`);
}

if (require.main === module) {
  seedTestMasters()
    .catch((e) => {
      console.error("Failed to seed TestMaster records:", e);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}
